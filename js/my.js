var lastIndex = 5;

function randomIndex() {
  var randomIndex;

  do {
    randomIndex = Math.floor(Math.random() * meals.length);
  } while (randomIndex === lastIndex);

  lastIndex = randomIndex;
  displayMeal(randomIndex);
}

function boxMessage(meal) {
  if (Number(meal.CookTime) >= 30) {
    document.getElementById("dangerMessage").innerHTML =
      `<div class="check-area message-prob bg-danger-subtle d-flex mt-2 gap-2"> <span class=" mt-2"
                          ><i class="fa-solid text-danger fa-xl fa-triangle-exclamation"></i>
                        </span>
                      <div>
                      <h6>Extended Preparation Time</h6>
                      <p>This recipe requires more than 30 minutes to prepare. Plan accordingly!</p>
                      </div></div>`;
  } else {
    document.getElementById("dangerMessage").innerHTML = ``;
  }
}
